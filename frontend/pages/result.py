"""
Result page component - displays meeting summary and details
"""
import streamlit as st
from fpdf import FPDF
import io
from components.header import render_header
from components.cards import render_card
from utils.api import ask_question, send_email
from utils.formatters import format_datetime, format_key_points, format_action_items, sanitize_for_pdf

def render_result_page():
    """Render the result page"""
    if not st.session_state.get('selected_meeting'):
        st.warning("No meeting selected")
        if st.button("← Back to Upload"):
            st.session_state.current_page = "upload"
            st.rerun()
        return
    
    meeting = st.session_state.selected_meeting
    
    # Header with back button
    col1, col2 = st.columns([4, 1])
    with col1:
        render_header(
            meeting.get('title', 'Meeting Summary'),
            f"Created: {format_datetime(meeting.get('created_at'))}"
        )
    with col2:
        if st.button("← Back", use_container_width=True):
            st.session_state.current_page = "upload"
            st.rerun()
    
    st.divider()
    
    # Tabs for different sections
    tab1, tab2, tab3 = st.tabs(["Summary", "Transcript", "Ask Questions"])
    
    with tab1:
        col1, col2 = st.columns(2)
        
        with col1:
            st.markdown("""
            <div class="professional-card">
                <div class="professional-card-header">
                    <h3 class="professional-card-title">
                        <span style="font-size: 1.5rem; margin-right: 0.5rem;">📝</span>Key Points
                    </h3>
                </div>
                <div class="professional-card-content">
            """, unsafe_allow_html=True)
            st.markdown(format_key_points(meeting.get('summary', '')), unsafe_allow_html=True)
            st.markdown("</div></div>", unsafe_allow_html=True)
        
        with col2:
            st.markdown("""
            <div class="professional-card">
                <div class="professional-card-header">
                    <h3 class="professional-card-title">
                        <span style="font-size: 1.5rem; margin-right: 0.5rem;">✅</span>Action Items
                    </h3>
                </div>
                <div class="professional-card-content">
            """, unsafe_allow_html=True)
            st.markdown(format_action_items(meeting.get('action_items', '')), unsafe_allow_html=True)
            st.markdown("</div></div>", unsafe_allow_html=True)
        
        # Export options
        st.divider()
        st.markdown("### Export Options")
        
        col1, col2, col3 = st.columns(3)
        
        with col1:
            # PDF Export with Unicode support
            try:
                pdf = FPDF()
                pdf.add_page()
                
                # Title
                title = sanitize_for_pdf(meeting.get('title', 'Meeting'))
                pdf.set_font("Arial", 'B', 16)
                pdf.cell(0, 10, f"Meeting Summary: {title}", ln=True, align='C')
                pdf.ln(5)
                
                # Date
                date_str = sanitize_for_pdf(format_datetime(meeting.get('created_at')))
                pdf.set_font("Arial", 'I', 10)
                pdf.cell(0, 10, f"Date: {date_str}", ln=True)
                pdf.ln(5)
                
                # Summary section
                pdf.set_font("Arial", 'B', 14)
                pdf.cell(0, 10, "KEY POINTS", ln=True)
                pdf.ln(3)
                pdf.set_font("Arial", '', 11)
                summary_text = sanitize_for_pdf(meeting.get('summary', ''))
                # Split into lines and handle long lines
                for line in summary_text.split('\n'):
                    if line.strip():
                        pdf.multi_cell(0, 7, line.strip())
                        pdf.ln(2)
                
                pdf.ln(5)
                
                # Action Items section
                pdf.set_font("Arial", 'B', 14)
                pdf.cell(0, 10, "ACTION ITEMS", ln=True)
                pdf.ln(3)
                pdf.set_font("Arial", '', 11)
                action_text = sanitize_for_pdf(meeting.get('action_items', ''))
                # Split into lines and handle long lines
                for line in action_text.split('\n'):
                    if line.strip():
                        pdf.multi_cell(0, 7, line.strip())
                        pdf.ln(2)
                
                pdf.ln(10)
                pdf.set_font("Arial", 'I', 8)
                pdf.cell(0, 10, "Generated by Meeting Organizer", align='C')
                
                pdf_output = bytes(pdf.output())
                st.download_button(
                    label="Export as PDF",
                    data=pdf_output,
                    file_name=f"Summary_{meeting.get('title', 'meeting')}.pdf",
                    mime="application/pdf",
                    use_container_width=True
                )
            except Exception as e:
                st.error(f"Error generating PDF: {str(e)}")
                st.caption("Please try again or use the copy feature instead.")
        
        with col2:
            # Copy to Clipboard
            st.markdown("**Copy Content**")
            full_text = f"SUMMARY:\n{meeting.get('summary')}\n\nACTION ITEMS:\n{meeting.get('action_items')}"
            st.text_area("Full Summary Text", full_text, height=100, label_visibility="collapsed", key="copy_text")
            st.caption("Select all and copy the text above")
        
        with col3:
            # Email Summary
            with st.expander("Email Summary"):
                recipient = st.text_input("Recipient Email", placeholder="colleague@example.com", key="email_input")
                if st.button("Send Email", use_container_width=True, key="send_email"):
                    if recipient:
                        with st.spinner("Sending email..."):
                            result = send_email(meeting['id'], recipient)
                            if result["success"]:
                                st.success("Email sent successfully!")
                            else:
                                st.error(f"Error: {result.get('error', 'Failed to send')}")
                    else:
                        st.warning("Please enter an email address")
    
    with tab2:
        render_card(
            "Full Transcript",
            f'<div style="max-height: 500px; overflow-y: auto; font-family: var(--font-mono); font-size: 0.875rem; line-height: 1.7; white-space: pre-wrap;">{meeting.get("transcript", "No transcript available")}</div>',
            "📜"
        )
    
    with tab3:
        st.markdown("""
        <div class="professional-card">
            <div class="professional-card-header">
                <h3 class="professional-card-title">
                    <span style="font-size: 1.5rem; margin-right: 0.5rem;">💬</span>Ask Questions
                </h3>
            </div>
            <div class="professional-card-content">
                <p style="margin-bottom: 1rem; color: #6B7280;">Ask questions about this meeting and get AI-powered answers based on the transcript.</p>
            </div>
        </div>
        """, unsafe_allow_html=True)
        
        question = st.text_input(
            "Your question",
            placeholder="e.g., What were the main decisions made?",
            key="question_input"
        )
        
        if st.button("Ask Question", type="primary", use_container_width=True, key="ask_button"):
            if question:
                with st.spinner("Analyzing meeting transcript..."):
                    result = ask_question(meeting['id'], question)
                    if result["success"]:
                        st.markdown("### Answer")
                        st.markdown(result["data"]["answer"])
                    else:
                        error_msg = result.get('error', 'Failed to get answer')
                        st.error(f"Error: {error_msg}")
                        # Show more details in expander for debugging
                        with st.expander("Error Details"):
                            st.code(str(result))
            else:
                st.warning("Please enter a question")

